case_error() {
    run_case "Ошибка OpenGL посреди кадра" "--frames 30 --fail-at-frame 5" \
'Приложение намеренно ломает OpenGL на пятом кадре. Окно закроется само.

Ожидаем в выводе ниже:
  * "Injecting OpenGL error on frame 5.";
  * "OpenGL errors while rendering frame 5: InvalidEnum" — ошибка названа на том же
    кадре, где возникла, а не при закрытии окна;
  * "GPU resources released." — ресурсы освободились даже при исключении.

Также ожидаем в терминале строку вида "Abort trap: 6 dotnet ..." — это macOS
сообщает о необработанном исключении, для этого кейса так и задумано.' log
}

# Порядок кейсов = порядок проверки. Список один, TOTAL считается из него.
CASES=(
    case_scene
    case_colors
    case_depth_off
    case_cull_on
    case_cull_front
    # case_cycles
    case_error
)

# Выбрать кейсы для прогона: все или только перечисленные номера (ONLY="7 9").
# Печатает пары "номер имя", номер сквозной по CASES — чтобы в заголовке был
# настоящий номер кейса, даже если прогон выборочный.
select_cases() {
    local n=0 name want
    for name in "${CASES[@]}"; do
        n=$((n + 1))
        if [ -z "${ONLY:-}" ]; then
            printf '%d %s\n' "$n" "$name"
            continue
        fi
        for want in $ONLY; do
            [ "$want" = "$n" ] && printf '%d %s\n' "$n" "$name"
        done
    done
}

# --- прогон -----------------------------------------------------------------

if [ ! -t 0 ]; then
    say "Нужен интерактивный терминал: отвечать y/n придётся вручную."
    say "Автоматическую проверку запускает bash spikes/OpenTkSpike/smoke-test.sh."
    exit 1
fi

mkdir -p "$OUT"

# Собираем сами: сценарий не зависит от Makefile. Вывод сборки в терминал не пускаем,
# при ошибке показываем его хвост — иначе падение осталось бы незамеченным.
dotnet build "$PROJECT" --configuration "$CONFIG" --nologo > "$OUT/build.log" 2>&1
if [ $? -ne 0 ] || [ ! -f "$APP" ]; then
    say "Сборка не удалась, лог: $OUT/build.log"
    tail -n 20 "$OUT/build.log"
    exit 1
fi

selected=()
while IFS= read -r entry; do
    selected+=("$entry")
done < <(select_cases)
TOTAL=${#selected[@]}

if [ "$TOTAL" -eq 0 ]; then
    say "ONLY=\"$ONLY\" не совпал ни с одним кейсом 1..${#CASES[@]}"
    exit 2
fi

line "="
say " Ручная проверка прототипа OpenTK (docs/spikes.md)"
line "="
say " $TOTAL кейсов, вывод каждого окна пишется в $OUT/case-N.log и в терминал не попадает."
say " Отвечайте y, если увиденное совпало с описанием, иначе любой другой символ — выход с ошибкой."
line "="

for entry in "${selected[@]}"; do
    CASE_NO="${entry%% *}"
    "${entry#* }"
done

say ""
line "="
say " Пройдено $PASSED из $TOTAL кейсов."
line "="
