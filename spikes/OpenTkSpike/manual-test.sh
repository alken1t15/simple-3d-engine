#!/usr/bin/env bash
# Ручная приёмка прототипа: окно запускается отдельным процессом, терминал спрашивает y/n.
#
# На каждый кейс скрипт:
#   1. печатает ожидаемое поведение;
#   2. запускает spike с --focus off в фоне, не блокируя терминал: окно не забирает фокус,
#      а вывод приложения уходит в файл кейса — в терминал ничего не попадает;
#   3. спрашивает y — одним символом, Enter жать не нужно; любой другой ответ — выход с ошибкой;
#   4. сам закрывает окно и сразу идёт дальше — крестик нажимать не нужно.
#
# Запуск из корня репозитория:
#   bash spikes/OpenTkSpike/manual-test.sh
#   CONFIG=Debug bash spikes/OpenTkSpike/manual-test.sh
#   ONLY="6 7" bash spikes/OpenTkSpike/manual-test.sh
#
# Скрипт самодостаточный: собирает spike сам, нужен только .NET 10 SDK и графический
# дисплей. Makefile запускать не нужно. В CI не запускается: автоматическую проверку
# того же делает smoke-test.sh, а этот сценарий — для глаз.
#
# Настраивается переменными окружения:
#   CONFIG=Release   конфигурация сборки spike
#   ONLY="6 7"       прогнать только указанные кейсы
#   TERM_WAIT=3     пауза между TERM и KILL, если приложение не завершилось
#   EXIT_WAIT=60    сколько ждать выхода в кейсах, где приложение закрывается само
#   POSITION=0,40   где открывать окно: "X,Y" в пунктах от левого верхнего угла экрана,
#                   чтобы терминал оставался на виду; пустое значение — положение выберет ОС
#
# Управление в окне прототипа: клик — фокус, ЛКМ+мышь — облет, колесо — зум, Space — пауза,
# D — depth, C — culling, T — текстура, Esc — выход.

set -uo pipefail

CONFIG="${CONFIG:-Release}"
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
PROJECT="$ROOT/spikes/OpenTkSpike"
APP="$PROJECT/bin/$CONFIG/net10.0/OpenTkSpike.dll"
OUT="${OUT:-$ROOT/artifacts/manual}"

# Сколько ждать выхода приложения в кейсах, где оно закрывается само.
EXIT_WAIT="${EXIT_WAIT:-60}"
# Пауза между TERM и KILL: оборванная на середине кадра отрисовка выглядит
# как падение, поэтому даём процессу время уйти тихо.
TERM_WAIT="${TERM_WAIT:-3}"
# Окно уводим в левый верхний угол, чтобы терминал с вопросом оставался на экране.
POSITION="${POSITION-0,40}"

APP_PID=""
CUR_TITLE=""
CUR_FLAGS=""
CUR_LOG=""
PASSED=0
CASE_NO=0

# --- вспомогательное --------------------------------------------------------

line() { printf '%*s\n' 78 '' | tr ' ' "$1"; }

say() { printf '%s\n' "$*"; }

stop_app() {
    [ -z "$APP_PID" ] && return 0

    kill -TERM "$APP_PID" 2>/dev/null
    local waited=0
    while kill -0 "$APP_PID" 2>/dev/null; do
        sleep 0.1
        waited=$((waited + 1))
        [ "$waited" -ge $((TERM_WAIT * 10)) ] && break
    done

    kill -KILL "$APP_PID" 2>/dev/null
    wait "$APP_PID" 2>/dev/null
    APP_PID=""
}

trap stop_app EXIT INT TERM

# Прочитать ровно один символ ответа, не дожидаясь Enter.
read_key() {
    if [ "${BASH_VERSINFO[0]}" -ge 4 ]; then
        IFS= read -r -n 1 key
    else
        local saved
        saved="$(stty -g)"
        stty -icanon min 1 time 0
        key="$(dd bs=1 count=1 2>/dev/null)"
        stty "$saved"
    fi

    printf '\n'
}

await_app() {
    local limit="$1" watchdog status
    (sleep "$limit"; kill -TERM "$APP_PID" 2>/dev/null) &
    watchdog=$!
    wait "$APP_PID"
    status=$?
    kill "$watchdog" 2>/dev/null
    wait "$watchdog" 2>/dev/null
    APP_PID=""
    return "$status"
}

fail() {
    say ""
    line "!"
    say "ПРОВАЛ: $1"
    say "Кейс: $CUR_TITLE"
    say "Ключи запуска: ${CUR_FLAGS:-—}"
    say "Вывод приложения: ${CUR_LOG:-—}"
    line "!"
    say "Пройдено $PASSED из $TOTAL кейсов. Ручная проверка не пройдена."
    exit 1
}

# Один кейс: заголовок, ключи запуска, ожидаемое поведение, режим показа.
# Режим window — смотрим на окно и отвечаем y, окно закрывает скрипт; log — приложение
# закрывается само, его вывод печатается здесь, и подтверждаем уже текст.
run_case() {
    local title="$1" flags="$2" expected="$3" mode="$4" key

    CUR_TITLE="$title"
    CUR_FLAGS="$flags"
    CUR_LOG="$OUT/case-$CASE_NO.log"

    say ""
    line "="
    say " Кейс $CASE_NO из ${#CASES[@]}: $title"
    [ -n "$flags" ] && say " Ключи запуска: $flags"
    say " Вывод приложения: $CUR_LOG"
    line "="
    say ""
    say "$expected"
    say ""

    rm -f "$CUR_LOG"
    # --focus off — окно не забирает фокус у терминала, поэтому y печатается сразу;
    # --position — окно открывается в левом верхнем углу, терминал остаётся на месте.
    # Вывод приложения уходит в файл кейса, в терминал ничего не попадает.
    # stdin приложению не нужен: иначе оно заберёт ввод терминала.
    # shellcheck disable=SC2086
    dotnet "$APP" $flags --focus off ${POSITION:+--position "$POSITION"} > "$CUR_LOG" 2>&1 < /dev/null &
    APP_PID=$!

    if [ "$mode" = log ]; then
        await_app "$EXIT_WAIT"
        say "Приложение закрыло окно само. Проверьте текст в $CUR_LOG."
        say ""
    else
        say "Окно открыто, вывод приложения пишется в файл кейса."
        say "Посмотрите на окно и нажмите y — окно закроет скрипт, Enter жать не нужно."
        say ""
    fi

    printf 'Совпало с описанием? [y/N] '
    key=""
    read_key

    case "$(printf '%s' "$key" | tr '[:upper:]' '[:lower:]')" in
        y) ;;
        *) fail "поведение не совпало с описанием" ;;
    esac

    if [ "$mode" = window ]; then
        # Окно закрывает скрипт: ждать крестик или Esc от человека не нужно.
        stop_app
    fi

    PASSED=$((PASSED + 1))
}

# --- кейсы -----------------------------------------------------------------
# Ожидаемое поведение описано так, как его видно на экране: без слов о коде.
# Сцена:
# * большой куб в центре (медленно вращается)
# * серая плоскость 3x3 через его середину
# * маленький оранжевый куб сзади слева
# * фон тёмно-синий.

case_scene() {
    run_case "Окно, сцена, камера" "" \
'Окно 800x600, фон тёмно-синий. В центре большой куб с буквой F на гранях,
он медленно вращается. Серая плоскость проходит ровно через середину куба.
Позади слева виден маленький оранжевый куб с той же текстурой.

Клавиши окна работают, только когда у него фокус: кликните по окну один раз,
дальше мышь и клавиши идут в окно, а y в терминале — по-прежнему сюда.

Проверьте мышью:
  * зажмите ЛКМ и поводите — сцена облетает вокруг центра, куб остаётся в центре и продолжает вращаться;
  * колесо — приближение и отдаление, кадр не дёргается;
  * Space останавливает вращение, Esc закрывает окно.
' window
}

case_colors() {
    run_case "Базовый цвет вместо текстуры" "--texture off" \
'Та же сцена, но без текстуры: каждая грань окрашена своим базовым цветом.

Ожидаем:
  * +X красный, -X голубой, +Y зелёный, -Y пурпурный, +Z синий, -Z жёлтый;
  * камера стоит со стороны +X/+Y/+Z, поэтому видны красная, зелёная и синяя;
  * плоскость осталась серой;
  * та же геометрия и тот же ракурс;
' window
}

case_depth_off() {
    run_case "Depth test выключен: почему он нужен" "--depth off" \
'Та же сцена с выключенным depth test — это заведомо сломанный режим.

Ожидаем (именно поломку):
  * плоскость, нарисованная последней, закрывает почти всю сцену;
  * на маленьком кубе видна зеркальная F задней грани поверх передней;
  * большой куб наполовину исчезает за плоскостью.' window
}

case_cull_on() {
    run_case "Back-face culling включён" "--cull on" \
'Задние грани отбрасываются.

Ожидаем:
  * картинка почти такая же, как с выключенным culling;
  * но плоскость видна только сверху — она исчезает при облете вниз.' window
}

case_cull_front() {
    run_case "Неверный обход граней" "--cull front" \
'Отбрасываются ЛИЦЕВЫЕ грани — заведомо неверный режим, имитирующий ошибку
порядка обхода треугольников.

Ожидаем:
  * сцена вывернута наизнанку: видны внутренние стороны граней;
  * куб выглядит пустым;
  * плоскость пропала, если смотреть сверху;
  * плоскость видна при взгляде снизу.
' window
}

